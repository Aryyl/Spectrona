# ---------------------------------------------------------------------------
# 2. GET /api/ecg/demo/analysis
# ---------------------------------------------------------------------------

@ecg_bp.route("/demo/analysis", methods=["GET"])
def demo_analysis() -> Response:
    """Return a rich hardcoded demo ECG analysis result for the requested scenario."""
    try:
        scenario_idx = int(request.args.get("scenario", 0))
    except (ValueError, TypeError):
        scenario_idx = 0
    scenario_idx = max(0, min(3, scenario_idx))
    return jsonify(_build_scenario(scenario_idx))


# ---------------------------------------------------------------------------
# 3. GET /api/ecg/history/<patient_id>
# ---------------------------------------------------------------------------

@ecg_bp.route("/history/<patient_id>", methods=["GET"])
def patient_history(patient_id: str) -> Response:
    """Return list of 8 demo recording summaries for the given patient."""
    if patient_id not in ("patient_01", "patient_02"):
        # Still return demo data for any unknown patient ID, using patient_01 format
        pass
    recordings = _history_for_patient(patient_id)
    return jsonify({
        "status": "ok",
        "patient_id": patient_id,
        "count": len(recordings),
        "recordings": recordings,
    })


# ---------------------------------------------------------------------------
# 4. POST /api/ecg/record/start  &  POST /api/ecg/record/stop
# ---------------------------------------------------------------------------

@ecg_bp.route("/record/start", methods=["POST"])
def record_start() -> Response:
    """Start a demo ECG recording session."""
    recording_id = f"ECG-LIVE-{int(time.time())}"
    return jsonify({
        "status": "ok",
        "recording_id": recording_id,
        "message": "Recording started",
    })


@ecg_bp.route("/record/stop", methods=["POST"])
def record_stop() -> Response:
    """Stop the current demo ECG recording session."""
    recording_id = f"ECG-LIVE-{int(time.time())}"
    return jsonify({
        "status": "ok",
        "recording_id": recording_id,
        "message": "Recording stopped",
    })


# ---------------------------------------------------------------------------
# 5. POST /api/ecg/analyze
# ---------------------------------------------------------------------------

@ecg_bp.route("/analyze", methods=["POST"])
def analyze() -> Response:
    """Accept any JSON body and return a scenario-0 analysis with a dynamic recording_id."""
    recording_id = f"ECG-LIVE-{int(time.time())}"
    result = _build_scenario(0, recording_id=recording_id)
    return jsonify(result)


# ---------------------------------------------------------------------------
# 6. GET /api/ecg/recording/<recording_id>
# ---------------------------------------------------------------------------

@ecg_bp.route("/recording/<recording_id>", methods=["GET"])
def get_recording(recording_id: str) -> Response:
    """Return full analysis detail for a given recording_id."""
    scenario_idx = _RECORDING_SCENARIO_MAP.get(recording_id, 0)
    result = _build_scenario(scenario_idx, recording_id=recording_id)
    return jsonify(result)
