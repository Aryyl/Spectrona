def _build_scenario(idx: int, recording_id: str | None = None, patient_id: str = "patient_01") -> dict:
    builder = _SCENARIO_BUILDERS.get(idx, _scenario_0)
    default_rid = f"ECG-DEMO-{2041 + idx}"
    return builder(recording_id or default_rid, patient_id)


